"""Writes art/IMPORT-CHECKLIST.md from the strip order (D94)."""


def write_checklist(order, art):
    T = []
    T.append("# Owner import checklist (D94)\n")
    T.append("Generated by `art/tools/build.py`. Do not hand-edit; re-run the script instead.\n")
    T.append("Why: the IDE owns the `.yyp`/`.yy` files, so agents cannot create sprites. Code looks each sprite up by name with")
    T.append("`asset_get_index(\"spr_icons_<category>\")` and draws a code fallback until the sprite exists. Do this once per strip, in any order.\n")
    T.append("## Steps for every strip (about 1 minute each)\n")
    T.append("1. Asset Browser: right-click the **Sprites** folder, **Create > Sprite**. Rename it to the exact name in the table below (`spr_icons_<category>`; case matters).")
    T.append("2. In the Sprite Editor press **Import** and pick `art/strips/<category>_strip.png`.")
    T.append("3. The **Import Strip Image** dialog appears. Set: *Number of frames* = the Frames column in the table; *Frames per row* = the same number (a single row);")
    T.append("   *Frame width* = 16, *Frame height* = 16; *Offset X/Y* = 0; *Separation X/Y* = 0. Check the preview shows one icon per frame, then **OK**.")
    T.append("   (If your IDE version words these differently, the rule is: one row, 16x16 cells, no offset, no separation.)")
    T.append("4. **Origin**: set the Origin dropdown to **Top Left** (0,0).")
    T.append("5. **Collision mask**: icons are only drawn, never collided with. Do not assign the sprite to any object and leave the default mask. If you want it explicit: Mode = Manual with all four bounds 0.")
    T.append("6. Playback: set the speed to 0 frames per second (it is a lookup table, not an animation). The code picks the frame with `draw_sprite(spr, index, x, y)`.")
    T.append("7. Texture group: leave Default. Save (Ctrl+S).\n")
    T.append("## Sprites to create\n")
    T.append("| Sprite name (exact) | Strip file | Frames | Frame size | Order file |")
    T.append("|---|---|---|---|---|")
    for cat, ids in order.items():
        T.append(f"| `spr_icons_{cat}` | `art/strips/{cat}_strip.png` | {len(ids)} | 16x16 | `art/strips/{cat}_strip.txt` |")
    T.append("| `spr_card_frame` | `art/icons/ui/card_frame.png` | 1 | 24x32 | single image: use plain Import, not Import Strip |")
    T.append("")
    T.append("`spr_card_frame` extra step: Sprite Editor > **9-slice** tab > enable, set Left = 8, Right = 8, Top = 8, Bottom = 8, centre stretch mode **Tile**.")
    T.append("The inside of the frame is transparent on purpose (code or the card art fills it).\n")
    T.append("## Frame index = position in the strip\n")
    T.append("Code reads the subimage index from this list (same data as `art/strips/manifest.json` and each `.txt`). Ids are the game's status and skill names.\n")
    for cat, ids in order.items():
        T.append(f"**spr_icons_{cat}**: " + ", ".join(f"{n}={i}" for n, i in enumerate(ids)) + "\n")
    T.append("`spr_icons_skill_up` has the same order as `spr_icons_skill`; it is the skill icon plus a small '+' corner badge, for upgraded cards (D82).\n")
    T.append("## After importing\n")
    T.append("Tell the agent 'strips imported'. The agent removes the code fallback for that category and runs the gate.")
    T.append("If a frame looks wrong in the IDE, the Import Strip numbers are off: delete the frames and import again with the table values.\n")
    T.append("## Provenance")
    T.append("")
    T.append("The final icons in `art/icons/` and the strips are script-drawn pixel art (`art/tools/draw.py`), not AI output. The SDXL images in `art/candidates/` are post-processed candidates only and are not in the strips. All files use exactly #071821 #306850 #86C06C #E0F8CF plus transparency (checked by `build.py`).")
    T.append("")
    with open(f"{art}/IMPORT-CHECKLIST.md", "w", newline="\n") as f:
        f.write("\n".join(T) + "\n")


