"""Writes the code fallback for the v2 icon strips (D94) into scripts/scr_fx/scr_fx.gml.

Why: the strips are not imported as sprites yet (the IDE owns .yy files), so the battle HUD and lists must still show the real
pixels. Icon_Rows(category, frame) returns 16 strings of 16 characters ('.' = clear, '0'..'3' = darkest..lightest palette colour);
Icon_Get builds a sprite from them at runtime until asset_get_index("spr_icons_<category>") finds the imported strip.

After the owner imports a strip: delete that category from this script's CATEGORIES (or the whole block once all are imported),
re-run it, and the generated block shrinks accordingly.

Run from the repo root:  python art/tools/gen_icon_fallback.py
"""
import json
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
STRIPS = ROOT / "art" / "strips_v2"
TARGET = ROOT / "scripts" / "scr_fx" / "scr_fx.gml"
BEGIN = "// ---- ICON FALLBACK BEGIN (generated by art/tools/gen_icon_fallback.py; do not edit by hand) ----"
END = "// ---- ICON FALLBACK END ----"
CATEGORIES = ["status", "skill", "throwable", "passive", "accessory", "misc"]   # skill_up is the same art plus a corner badge: not needed by the HUD
PALETTE = {(7, 24, 33): "0", (48, 104, 80): "1", (134, 192, 108): "2", (224, 248, 207): "3"}


def rows_of(im, frame):
    out = []
    for y in range(16):
        row = ""
        for x in range(16):
            r, g, b, a = im.getpixel((frame * 16 + x, y))
            if a < 128:
                row += "."
            else:
                row += PALETTE[(r, g, b)]
        out.append(row)
    return out


def main():
    manifest = json.loads((STRIPS / "manifest.json").read_text(encoding="utf-8"))
    lines = [BEGIN,
             "// Frames per category are in the order of art/strips_v2/<category>_strip.txt (art/IMPORT-CHECKLIST.md).",
             "function Icon_FallbackData() {",
             "    if (variable_global_exists(\"icon_fb_data\")) return global.icon_fb_data;",
             "    var d = {};"]
    for cat in CATEGORIES:
        meta = manifest["spr_icons_" + cat]
        im = Image.open(STRIPS / (cat + "_strip.png")).convert("RGBA")
        frames = meta["frames"]
        if im.size != (16 * frames, 16):
            sys.exit("bad strip size for " + cat + ": " + str(im.size))
        lines.append("    d." + cat + " = {")
        lines.append("        ids: [" + ", ".join('"' + i + '"' for i in meta["ids"]) + "],")
        lines.append("        rows: [")
        for f in range(frames):
            lines.append("            [" + ", ".join('"' + r + '"' for r in rows_of(im, f)) + "]" + ("," if f < frames - 1 else ""))
        lines.append("        ]")
        lines.append("    };")
    lines.append("    global.icon_fb_data = d;")
    lines.append("    return d;")
    lines.append("}")
    lines.append(END)
    block = "\n".join(lines) + "\n"

    text = TARGET.read_text(encoding="utf-8")
    if BEGIN in text:
        head = text[:text.index(BEGIN)]
        tail = text[text.index(END) + len(END):].lstrip("\n")
        text = head + block + ("\n" + tail if tail else "")
    else:
        text = text.rstrip("\n") + "\n\n" + block
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", TARGET, "with", len(lines), "lines")


if __name__ == "__main__":
    main()
