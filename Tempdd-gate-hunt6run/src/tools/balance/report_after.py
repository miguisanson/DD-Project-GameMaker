#!/usr/bin/env python3
"""Appends (or replaces) section 6 "After D111" of .planning/research/balance-report.md: the game BEFORE the owner-approved balance (the committed
tools/balance/export_data_before_d111.json) against the game AFTER it (tools/balance/export_data.json), both against tools/balance/targets.json.

  python tools/balance/report_after.py                 400 runs per class x profile cell
  python tools/balance/report_after.py --runs 120      a quick draft
  python tools/balance/report_after.py --out FILE

report.py is the E1 generator: it wrote sections 0-5 for the data of that day (before D111) and its proposals are what-ifs on top of the CURRENT data, so do not
re-run it against the post-D111 snapshot. This script is what to run after a balance change.
"""
import argparse
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sim  # noqa: E402
import report  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, ".planning", "research", "balance-report.md")
BEFORE = os.path.join(HERE, "export_data_before_d111.json")
CLASSES = report.CLASSES
PROFILES = report.PROFILES
MARK = "## 6. After D111"
NOTE = ("> **D111 and D112 are applied (section 6).** Sections 0-5 were written on the data of 2026-10-14, before the owner approved E1-1 .. E1-6; "
        "their \"today\" is the game before D111 and their proposals are now in the game. E1-7 (Mage HP die) and E1-8 (economy) were not approved.")


def is_pct(metric_id):
    return metric_id in ("normal_fight_win_rate", "run_win_rate") or metric_id.startswith("class_spread")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=400)
    ap.add_argument("--seed", type=int, default=20261014)
    ap.add_argument("--jobs", type=int, default=max(1, min(8, (os.cpu_count() or 2) - 1)))
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--before", default=BEFORE)
    a = ap.parse_args()
    t0 = time.time()
    T = sim.load_targets()

    def log(m):
        print("[%4.0fs] %s" % (time.time() - t0, m), file=sys.stderr)

    log("before D111, greedy")
    b = sim.build_table(a.before, CLASSES, PROFILES, a.runs, a.seed, a.jobs, quiet=True)
    log("after D111, greedy")
    n = sim.build_table(sim.DEFAULT_DATA, CLASSES, PROFILES, a.runs, a.seed, a.jobs, quiet=True)
    log("basic-attack-only, before and after")
    bb = sim.build_table(a.before, CLASSES, ["average"], a.runs, a.seed, a.jobs, policy="basic", quiet=True)
    nb = sim.build_table(sim.DEFAULT_DATA, CLASSES, ["average"], a.runs, a.seed, a.jobs, policy="basic", quiet=True)
    d_after = sim.Data(sim.DEFAULT_DATA)

    rows_b, res_b = report.verdict_rows(b, T)
    rows_a, res_a = report.verdict_rows(n, T)
    rows = [[ra[0], ra[1], rb[2], ra[2], ra[3]] for rb, ra in zip(rows_b, rows_a)]
    bad_b = [r for r in res_b if not r["ok"]]
    bad_a = [r for r in res_a if not r["ok"]]

    L = []
    w = L.append
    w(MARK + " (the owner-approved balance is in the game)")
    w("")
    w("Generated by `python tools/balance/report_after.py` (after = `tools/balance/export_data.json`, build `%s`; before = `tools/balance/export_data_before_d111.json`; "
      "seed %d, %d runs per class x profile cell, greedy policy). The targets are the current `tools/balance/targets.json`, which since **D112** says a winning run "
      "takes **25-30 minutes** (the before column is judged against the same new bands)." % (d_after.build, a.seed, a.runs))
    w("")
    w("What changed in the game (D111 = E1-1 .. E1-6; E1-7 and E1-8 were not approved):")
    w("")
    w(report.md_table(["change", "before", "after"], [
        ["Palehorn base HP / DEF", "25 / 16", "55 / 18"],
        ["Pale Choirbeast base HP / DEF", "34 / 18", "140 / 24"],
        ["ELITE_HP_MULT (new; `Elite_Apply` sets max HP = round half up(max HP x mult))", "- (x1)", "1.8"],
        ["enemy basic_power: Slime, Spider, Snake, Dire Wolf", "3", "5"],
        ["enemy basic_power: Mad Whisp, Killer Plant, Ghost Sword, Stranger", "5", "7"],
        ["enemy basic_power: Palehorn (unchanged) / Pale Choirbeast", "7 / 9", "7 / 14"],
        ["power_mult of Vine Trap, Cut, Ramming, Pale Hymn", "1.5", "2.0"],
        ["Knight base SPD", "8", "10"],
        ["Nobody fixed growth per level", "1 point (ATK, DEF, SPD, MAG cycle)", "2 points (the cycle point and the one two steps on)"],
        ["THROW_NOBODY_MULT", "1.5", "2.0"],
        ["targets.json run_minutes (D112)", "45-60", "25-30"],
    ]))
    w("")
    w("### 6.1 Run win rate by class and skill profile (95% interval)")
    w("")
    w("After:")
    w("")
    w(report.table_win(n))
    w("")
    w("Before: " + "; ".join("%s %s/%s/%s" % (c, report.pct(b[(c, "novice")]["win_rate"]), report.pct(b[(c, "average")]["win_rate"]), report.pct(b[(c, "expert")]["win_rate"])) for c in CLASSES) + " (novice/average/expert).")
    w("")
    w("### 6.2 Fight length (mean player turns of won fights / win rate, average profile)")
    w("")
    w("After:")
    w("")
    w(report.table_fights(n))
    w("")
    w("Before:")
    w("")
    w(report.table_fights(b))
    w("")
    w("### 6.3 Pace, levels, resources (average profile)")
    w("")
    w("After:")
    w("")
    w(report.table_levels(n))
    w("")
    w("Before:")
    w("")
    w(report.table_levels(b))
    w("")
    w("### 6.4 Every metric against its target band (cells in band: before / after)")
    w("")
    w(report.md_table(["metric", "target band", "before", "after", "values after"], rows))
    w("")
    w("**Checks outside their band: %d of %d after D111 (%d of %d before).**" % (len(bad_a), len(res_a), len(bad_b), len(res_b)))
    w("")
    if bad_a:
        w("Still outside their band after D111:")
        w("")
        for r in bad_a:
            v = r["value"]
            band = r["band"]
            if is_pct(r["id"]):
                txt = "%.1f%%" % (100 * v)
                btxt = "%.0f-%.0f%%" % (100 * band[0], 100 * band[1])
            else:
                txt = ("%.1f" % v) if isinstance(v, float) else str(v)
                btxt = "%s-%s" % (band[0], band[1])
            cell = r["cell"][0] + ("/" + r["cell"][1] if r["cell"][1] not in ("all", None, "") else "")
            w("- %s, %s: %s (band %s)%s" % (r["id"], cell, txt, btxt, (" " + str(r["note"])) if r.get("note") else ""))
        w("")
    w("### 6.5 Basic-attack-only players (average profile run win rate)")
    w("")
    w("; ".join("%s %s (before %s)" % (c, report.pct(nb[(c, "average")]["win_rate"]), report.pct(bb[(c, "average")]["win_rate"])) for c in CLASSES) + ".")
    w("")
    w("### 6.6 Reproduce")
    w("")
    w("```")
    w("powershell -NoProfile -ExecutionPolicy Bypass -File tools/automation/run_tests.ps1 -Mode fast -Only exportdata -WorkRoot E:\\Temp\\dd-gate-bal")
    w("python tools/balance/sim.py --snapshot E:\\Temp\\dd-gate-bal\\export\\export_data.json   # tools/balance/export_data.json")
    w("python tools/balance/sim.py --vectors")
    w("python tools/balance/sim.py --check                    # exit 1 when a number is outside tools/balance/targets.json")
    w("python tools/balance/report_after.py                   # this section")
    w("```")
    w("")
    section = "\n".join(L)

    with open(a.out, encoding="utf-8") as f:
        text = f.read()
    i = text.find("\n" + MARK)
    if i >= 0:
        text = text[:i + 1]
    elif not text.endswith("\n"):
        text += "\n"
    if NOTE not in text:
        head, _, rest = text.partition("\n")
        text = head + "\n\n" + NOTE + "\n" + rest
    text = text.rstrip("\n") + "\n\n" + section
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    log("wrote " + a.out)


if __name__ == "__main__":
    main()
